#ifndef OPENMESH_NETCONF_H
#define OPENMESH_NETCONF_H

#include <stdbool.h>
#include <stdint.h>

#include <libubox/uloop.h>

#include "identity.h"

#define OM_TXN_TIMEOUT 30	/* seconds to confirm or auto-rollback */

/* om-managed named UCI sections (mode B); keep in sync with netconf.c */
#define OM_BAT_IF  "om_bat"	/* proto batadv soft interface */
#define OM_MESH_IF "om_mesh"	/* proto batadv_hardif carrier */

/* backhaul modes (ADR-0002) */
#define OM_BH_WIFI   0		/* mode A: 802.11s bridged to lan */
#define OM_BH_HYBRID 1		/* mode B: 802.11s + wired under batman-adv */

struct om_netconf {
	bool active;
	bool committed;
	uint32_t generation;
	char marker[OM_PATH_MAX];
	char bak_files[2][OM_PATH_MAX];
	char dest_files[2][OM_PATH_MAX];
	int n_files;
	struct uloop_timeout timer;
	void (*on_done)(bool committed, uint32_t generation, void *priv);
	void *priv;
};

/*
 * One-shot transaction: snapshot the affected /etc/config files, add an
 * om-managed 802.11s interface (mode A) or full batman-adv transport
 * (mode B), commit and reload. Without om_netconf_confirm() within
 * OM_TXN_TIMEOUT seconds everything is restored.
 * band: "5g" | "2g" | "auto". mode: OM_BH_WIFI | OM_BH_HYBRID.
 * Returns 0 / -1.
 */
int om_netconf_mesh_apply(struct om_netconf *nc, const char *state_dir,
			  const char *mesh_id, const char *band,
			  const char *sae_key, int mode);

/*
 * Apply 802.11k/v/r roaming options to all AP-mode wifi-ifaces under
 * the same transaction safety net. domain: 4 hex chars (FT mobility
 * domain), generated by the caller if empty. Returns 0 / -1.
 */
int om_netconf_roaming_apply(struct om_netconf *nc, const char *state_dir,
			     bool k, bool v, bool r, const char *domain);

/* Keep the just-applied configuration. Returns 0 / -1. */
int om_netconf_confirm(struct om_netconf *nc);

/* Restore the snapshot immediately (also used by the deadline timer). */
int om_netconf_rollback(struct om_netconf *nc);

/*
 * Boot-time recovery: if a previous transaction never got confirmed
 * (power loss), restore its snapshot. Call before uloop_run.
 */
void om_netconf_recover(struct om_netconf *nc, const char *state_dir);

#endif /* OPENMESH_NETCONF_H */
